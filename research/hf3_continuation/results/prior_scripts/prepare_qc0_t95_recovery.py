#!/usr/bin/env python3
# -*- coding: utf-8 -*-

from __future__ import annotations
import argparse
import json
import re
from pathlib import Path

VERSION = "BH-HF3-R6-T70-T95-RECOVERY-V1-2026-09-06"

EXPECTED_IT = 35840
EXPECTED_START_M = 70.0
TARGET_FINAL_M = 95.0
EXPECTED_FINAL_IT = 48640
RECOVER_BASENAME = "checkpoint.chkpt"

T_CH = 18.625
SOURCE_TAU = (0.25, 7.0)
RADII = [15.0, 30.0, 40.0, 50.0, 60.0, 70.0]

KERR_PERIOD_M = 11.677777461966803
PEAKS = {
    "r15": 42.25,
    "r30": 58.25,
    "r40": 69.00,
}


def replace_or_fail(text: str, pattern: str, replacement: str, label: str) -> str:
    new, n = re.subn(pattern, replacement, text, flags=re.MULTILINE)
    if n != 1:
        raise RuntimeError(
            f"{label}: ожидалась ровно 1 замена, найдено {n}. "
            "Создание потенциально опасного .par остановлено."
        )
    return new


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--source-par",
        default="/mnt/c/Users/Admin/qc0-horizon-multipoles-lite-t70-recover.par",
    )
    ap.add_argument(
        "--recovery-dir",
        default="/home/alex/simulations/qc0_lite_t70_recover",
    )
    ap.add_argument(
        "--output-par",
        default="/mnt/c/Users/Admin/qc0-horizon-multipoles-lite-t95-recover.par",
    )
    ap.add_argument(
        "--manifest",
        default="/mnt/c/Users/Admin/qc0-horizon-multipoles-lite-t95-recovery_manifest.json",
    )
    ap.add_argument(
        "--new-output-dir",
        default="/home/alex/simulations/qc0_lite_t95_recover",
    )
    args = ap.parse_args()

    source_par = Path(args.source_par)
    recovery_dir = Path(args.recovery_dir)
    output_par = Path(args.output_par)
    manifest_path = Path(args.manifest)
    new_output_dir = args.new_output_dir.rstrip("/")

    if not source_par.is_file():
        raise FileNotFoundError(f"Не найден исходный .par: {source_par}")
    if not recovery_dir.is_dir():
        raise FileNotFoundError(f"Не найден каталог восстановления: {recovery_dir}")

    chk = sorted(
        recovery_dir.glob(
            f"{RECOVER_BASENAME}.it_{EXPECTED_IT}.file_*.h5"
        )
    )
    if len(chk) < 2:
        raise RuntimeError(
            f"Для iteration {EXPECTED_IT} ожидалось не менее 2 checkpoint-файлов, "
            f"найдено {len(chk)}."
        )
    if any(p.stat().st_size <= 0 for p in chk):
        raise RuntimeError("Обнаружен пустой checkpoint-файл.")

    text = source_par.read_text(encoding="utf-8", errors="replace")

    text = replace_or_fail(
        text,
        r'^\s*Cactus::cctk_final_time\s*=\s*[^\n#]+',
        f'Cactus::cctk_final_time = {TARGET_FINAL_M:g}',
        "Cactus::cctk_final_time",
    )
    text = replace_or_fail(
        text,
        r'^\s*IO::out_dir\s*=\s*"[^"]*"',
        f'IO::out_dir = "{new_output_dir}"',
        "IO::out_dir",
    )
    text = replace_or_fail(
        text,
        r'^\s*IO::checkpoint_dir\s*=\s*"[^"]*"',
        f'IO::checkpoint_dir = "{new_output_dir}"',
        "IO::checkpoint_dir",
    )
    text = replace_or_fail(
        text,
        r'^\s*IO::recover_dir\s*=\s*"[^"]*"',
        f'IO::recover_dir = "{recovery_dir}"',
        "IO::recover_dir",
    )
    text = replace_or_fail(
        text,
        r'^\s*IO::recover_file\s*=\s*"[^"]*"',
        f'IO::recover_file = "{RECOVER_BASENAME}"',
        "IO::recover_file",
    )
    text = replace_or_fail(
        text,
        r'^\s*IO::recover\s*=\s*[^\n#]+',
        'IO::recover = "auto"',
        "IO::recover",
    )
    text = replace_or_fail(
        text,
        r'^\s*IO::recover_and_remove\s*=\s*[^\n#]+',
        "IO::recover_and_remove = no",
        "IO::recover_and_remove",
    )
    text = replace_or_fail(
        text,
        r'^\s*IO::truncate_files_after_recovering\s*=\s*[^\n#]+',
        "IO::truncate_files_after_recovering = no",
        "IO::truncate_files_after_recovering",
    )

    header = (
        "# ================================================================\n"
        "# BH-HF3-R6 strict recovery: t=70 M -> t=95 M\n"
        f"# Generated by {VERSION}\n"
        f"# Recovery checkpoint iteration: {EXPECTED_IT}\n"
        f"# Recovery source: {recovery_dir}\n"
        f"# New output: {new_output_dir}\n"
        "# ВАЖНО: восстановление должно начаться около t=70 M, а не t=0.\n"
        "# ================================================================\n\n"
    )

    output_par.parent.mkdir(parents=True, exist_ok=True)
    output_par.write_text(header + text, encoding="utf-8")

    source_start = T_CH + SOURCE_TAU[0]
    source_end = T_CH + SOURCE_TAU[1]

    causal_windows = {}
    for r in RADII:
        causal_windows[str(int(r))] = {
            "radius_M": r,
            "flat_arrival_start_M": source_start + r,
            "flat_arrival_end_M": source_end + r,
            "full_window_available_at_95M":
                bool(TARGET_FINAL_M >= source_end + r),
            "tail_after_flat_window_end_M":
                float(TARGET_FINAL_M - (source_end + r)),
        }

    late_periods = {
        key: {
            "peak_time_M": peak,
            "two_periods_end_M": peak + 2.0 * KERR_PERIOD_M,
            "three_periods_end_M": peak + 3.0 * KERR_PERIOD_M,
            "periods_available_at_95M":
                (TARGET_FINAL_M - peak) / KERR_PERIOD_M,
        }
        for key, peak in PEAKS.items()
    }

    manifest = {
        "stage": "BH-HF3-R6",
        "version": VERSION,
        "source_parameter_file": str(source_par),
        "generated_parameter_file": str(output_par),
        "recovery_directory": str(recovery_dir),
        "recovery_file_basename": RECOVER_BASENAME,
        "recovery_iteration": EXPECTED_IT,
        "checkpoint_files": [str(p) for p in chk],
        "checkpoint_sizes_bytes": {str(p): p.stat().st_size for p in chk},
        "expected_start_time_M": EXPECTED_START_M,
        "target_final_time_M": TARGET_FINAL_M,
        "expected_final_iteration_if_step_unchanged": EXPECTED_FINAL_IT,
        "new_output_directory": new_output_dir,
        "recover_and_remove": False,
        "truncate_files_after_recovering": False,
        "scientific_goal": {
            "kerr_period_M": KERR_PERIOD_M,
            "late_period_coverage": late_periods,
            "causal_windows": causal_windows,
            "reason": (
                "R5C подтвердил устойчивое приближение r=15M к Kerr, но точное "
                "фиксированное одно-модовое замыкание не достигнуто. При 70M "
                "r=30M имеет только ~1.006 периода после максимума, а r=40M "
                "только ~0.086 периода. t=95M даёт >3 периода на r=30M и "
                ">2 периода на r=40M, что необходимо для поздней "
                "многорадиусной проверки."
            ),
        },
    }

    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    manifest_path.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print("=" * 80)
    print("BH-HF3-R6 t70 -> t95 ПОДГОТОВКА ГОТОВА")
    print("=" * 80)
    print(f"Checkpoint iteration: {EXPECTED_IT}")
    print(f"Checkpoint file count: {len(chk)}")
    for p in chk:
        print(f"  {p}  ({p.stat().st_size / 1024**3:.3f} GiB)")
    print()
    print("Создан .par:")
    print(output_par)
    print()
    print("Создан manifest:")
    print(manifest_path)
    print()
    print("Новый каталог вывода:")
    print(new_output_dir)
    print()
    print(f"Целевое конечное время: {TARGET_FINAL_M:.1f} M")
    print(f"Ожидаемая конечная iteration при прежнем шаге: {EXPECTED_FINAL_IT}")
    print()
    print("Позднее покрытие по данным R5C:")
    for key, d in late_periods.items():
        print(
            f"  {key}: пик={d['peak_time_M']:.3f}M, "
            f"2 периода до {d['two_periods_end_M']:.3f}M, "
            f"периодов к 95M={d['periods_available_at_95M']:.3f}"
        )
    print()
    print("Причинные окна:")
    for r in RADII:
        d = causal_windows[str(int(r))]
        print(
            f"  r={r:.0f}M: "
            f"{d['flat_arrival_start_M']:.3f}..{d['flat_arrival_end_M']:.3f}M, "
            f"полное окно={d['full_window_available_at_95M']}"
        )
    print()
    print("ДЛИТЕЛЬНЫЙ РАСЧЁТ ПОКА НЕ ЗАПУСКАЙТЕ.")
    print("Сначала пришлите этот вывод в ChatGPT.")


if __name__ == "__main__":
    main()
